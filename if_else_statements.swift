// if statement

let age = 20
if age >= 18 {
    print("Eligible to vote")
}

//If-else statement

let number = 7
if number % 2 == 0 {
    print("Even number")
} else {
    print("Odd number")
}

//Else-if ladder

let mark = 85
if mark >= 90 {
    print("Grade A")
} else if mark >= 80 {
    print("Grade B")
} else if mark >= 70 {
    print("Grade C")
} else if mark >= 50 {
    print("Grade D")
} else {
    print("Fail")
}
